#!/usr/bin/env python3
"""Generate GD32 pin tables from a pins.csv file.

pins.csv format:  Name,PA0   (Name is the MicroPython-visible name)
Produces:
  genhdr/pin_table.h            - X-macro rows for the pin object table
  genhdr/pins.h                 - named pin constants (mp_rom_map_elem_t)
"""
import sys, os, csv

PORT_CHARS = "ABCDEFGHI"

def parse_port_num(s):
    s = s.strip()
    if len(s) < 3 or s[0] != 'P':
        raise ValueError("bad pin spec: %r" % s)
    port = PORT_CHARS.index(s[1])
    num = int(s[2:])
    return port, num

def main():
    if len(sys.argv) != 4:
        print("usage: gen_pins.py <pins.csv> <out_dir> <board>")
        sys.exit(1)
    csv_path, out_dir, board = sys.argv[1], sys.argv[2], sys.argv[3]
    os.makedirs(out_dir, exist_ok=True)

    rows = []       # (name, port, num)
    with open(csv_path, newline='') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            parts = [p.strip() for p in line.split(',')]
            if len(parts) < 2:
                continue
            name, spec = parts[0], parts[1]
            try:
                port, num = parse_port_num(spec)
            except (ValueError, IndexError):
                continue
            rows.append((name, port, num))

    # dedupe by encoded value, keep first name
    seen = set()
    uniq = []
    for name, port, num in rows:
        enc = (port << 4) | num
        if enc in seen:
            continue
        seen.add(enc)
        uniq.append((name, port, num))

    # pin_table.h - X macro rows for the object table
    with open(os.path.join(out_dir, "pin_table.h"), "w") as f:
        f.write("// auto-generated by gen_pins.py -- do not edit\n")
        for name, port, num in uniq:
            f.write("PIN_ROW(%s, %d, %d)\n" % (name, port, num))

    # pins.h - board pin name dict
    with open(os.path.join(out_dir, "pins.h"), "w") as f:
        f.write("// auto-generated by gen_pins.py -- do not edit\n")
        f.write("#ifndef MICROPY_INCLUDED_GD32_GENHDR_PINS_H\n")
        f.write("#define MICROPY_INCLUDED_GD32_GENHDR_PINS_H\n\n")
        f.write("const mp_rom_map_elem_t machine_pin_board_pins_locals_dict_table[] = {\n")
        for name, port, num in uniq:
            enc = (port << 4) | num
            safe = name if name.replace('_','').isalnum() else "PIN_%d" % enc
            f.write("    { MP_ROM_QSTR(MP_QSTR_%s), MP_ROM_INT(%d) },\n" % (safe, enc))
        f.write("};\n")
        f.write("#endif\n")

    print("generated %d pins for board %s" % (len(uniq), board))

if __name__ == "__main__":
    main()
