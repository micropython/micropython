# Build a 14-bit mask of which condition codes hold after a single CMP.
#
# CMP is the only instruction here that writes NZCV: mov (ORR), orr and lsl
# are flag-neutral, and b/b<cc> do not touch the flags either, so the whole
# mask can be built from one compare.
#
# Bit order: eq ne cs cc mi pl vs vc hi ls ge lt gt le


@micropython.asm_aarch64
def cc_mask(x0, x1):
    mov(x2, 0)
    mov(x3, 1)
    cmp(x0, x1)
    beq(set0)
    b(next0)
    label(set0)
    orr(x2, x2, x3)
    label(next0)
    lsl(x3, x3, 1)
    bne(set1)
    b(next1)
    label(set1)
    orr(x2, x2, x3)
    label(next1)
    lsl(x3, x3, 1)
    bcs(set2)
    b(next2)
    label(set2)
    orr(x2, x2, x3)
    label(next2)
    lsl(x3, x3, 1)
    bcc(set3)
    b(next3)
    label(set3)
    orr(x2, x2, x3)
    label(next3)
    lsl(x3, x3, 1)
    bmi(set4)
    b(next4)
    label(set4)
    orr(x2, x2, x3)
    label(next4)
    lsl(x3, x3, 1)
    bpl(set5)
    b(next5)
    label(set5)
    orr(x2, x2, x3)
    label(next5)
    lsl(x3, x3, 1)
    bvs(set6)
    b(next6)
    label(set6)
    orr(x2, x2, x3)
    label(next6)
    lsl(x3, x3, 1)
    bvc(set7)
    b(next7)
    label(set7)
    orr(x2, x2, x3)
    label(next7)
    lsl(x3, x3, 1)
    bhi(set8)
    b(next8)
    label(set8)
    orr(x2, x2, x3)
    label(next8)
    lsl(x3, x3, 1)
    bls(set9)
    b(next9)
    label(set9)
    orr(x2, x2, x3)
    label(next9)
    lsl(x3, x3, 1)
    bge(set10)
    b(next10)
    label(set10)
    orr(x2, x2, x3)
    label(next10)
    lsl(x3, x3, 1)
    blt(set11)
    b(next11)
    label(set11)
    orr(x2, x2, x3)
    label(next11)
    lsl(x3, x3, 1)
    bgt(set12)
    b(next12)
    label(set12)
    orr(x2, x2, x3)
    label(next12)
    lsl(x3, x3, 1)
    ble(set13)
    b(next13)
    label(set13)
    orr(x2, x2, x3)
    label(next13)
    lsl(x3, x3, 1)
    mov(x0, x2)


# bhs/blo are ARM aliases for bcs/bcc; check they behave identically.
@micropython.asm_aarch64
def carry_alias(x0, x1):
    mov(x2, 0)
    cmp(x0, x1)
    bhs(hs_set)
    b(hs_next)
    label(hs_set)
    mov(x2, 1)
    label(hs_next)
    cmp(x0, x1)
    blo(lo_set)
    b(lo_next)
    label(lo_set)
    add(x2, x2, 2)
    label(lo_next)
    mov(x0, x2)


